import math

def fmt(x, nd=4):
    return f"{x:.{nd}f}"

# ================================================================
# 实验一: 默里定律能耗 (shape.md 实验一输出)
#   ρ=0.50: 阻力 188813422580.1  维护 2.0   总 188813422582.1
#   ρ=0.79: 阻力 13184089.2      维护 45.0  总 13184134.2
#   ρ=0.90: 阻力 103100.4        维护 323.7 总 103424.1
# 代码: compute_energy_cost = Σ n_k/r_k^4 + Σ n_k·r_k^2 (10 级分叉, r_k = ρ^k)
# ================================================================
print("=" * 72)
print("[1] 重现实验一: 两成本全局扫描模型 (阻力 Σn/r⁴ + 维护 Σn·r²)")
print("=" * 72)
N_GEN = 10

def shape_resistance(rho, ngen=N_GEN):
    """Σ_{k=0..ngen} 2^k · ρ^(-4k) —— 阻力形状"""
    return sum(2.0 ** k * rho ** (-4 * k) for k in range(ngen + 1))

def shape_maintenance(rho, ngen=N_GEN):
    """Σ_{k=0..ngen} 2^k · ρ^(2k) —— 维护形状"""
    return sum(2.0 ** k * rho ** (2 * k) for k in range(ngen + 1))

print(f"  {fmt(0.50)}: 阻力={shape_resistance(0.50):.1f} 维护={shape_maintenance(0.50):.1f}")
print(f"  {fmt(0.79)}: 阻力={shape_resistance(0.79):.1f} 维护={shape_maintenance(0.79):.1f}")
print(f"  {fmt(0.90)}: 阻力={shape_resistance(0.90):.1f} 维护={shape_maintenance(0.90):.1f}")
print("  (实验原始值: 0.50→188813422580.1/2.0; 0.79→13184089.2/45.0; 0.90→103100.4/323.7)")
print("  注意: 实验代码里阻力系数未归一 (a=1), 这里形状一致, 比例关系相同)")

# 细网格扫描全局最小值 (两成本模型)
best_rho, best_cost = 0.5, float("inf")
for i in range(500, 1001):
    rho = i / 1000.0
    c = shape_resistance(rho) + shape_maintenance(rho)
    if c < best_cost:
        best_cost, best_rho = c, rho
print(f"\n  >>> 两成本全局扫描最小值: ρ* = {best_rho:.3f} (总能耗 {best_cost:.1f})")
print(f"  >>> 与文章声称的 0.79 比较: {'匹配' if abs(best_rho - 0.7937) < 0.01 else '不匹配!'}")
print(f"  >>> 诚实结论: 两成本全局扫描模型的最小值 ≠ 0.79 —— 这正是 shape.md")
print(f"      作者承认的悖论 (0.90 总能耗 103424 < 0.79 的 13184134)。")
print(f"      '0.79 是最优' 在此模型下【未被验证】。")

